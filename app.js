function parseVisibility(tokens, i) {
  if (tokens[i] === "CAVOK")
    return {
      used: 1,
      data: {
        code: "CAVOK",
        miles: null,
        display: "10 km or more",
        sub: "No significant weather/cloud below CAVOK limits",
        cavok: true,
      },
    };
  let code = tokens[i],
    m = code.match(/^(M|P)?(\d+)?(?:\s)?(\d\/\d)?SM$/);
  if (m) {
    let val = 0;
    if (m[2]) val += Number(m[2]);
    if (m[3]) {
      let [a, b] = m[3].split("/").map(Number);
      val += a / b;
    }
    return {
      used: 1,
      data: {
        code,
        miles: val,
        display: `${m[1] === "M" ? "< " : m[1] === "P" ? "> " : ""}${val} statute mile${val === 1 ? "" : "s"}`,
      },
    };
  }
  if (/^\d+$/.test(code) && tokens[i + 1] && /^\d\/\dSM$/.test(tokens[i + 1])) {
    let [a, b] = tokens[i + 1].replace("SM", "").split("/").map(Number),
      val = Number(code) + a / b;
    return {
      used: 2,
      data: {
        code: `${code} ${tokens[i + 1]}`,
        miles: val,
        display: `${val} statute miles`,
      },
    };
  }
  if (/^\d{4}$/.test(code)) {
    return {
      used: 1,
      data: {
        code,
        miles: null,
        display: `${Number(code) / 1000} km`,
        meters: Number(code),
      },
    };
  }
  return null;
}

function decodeWeather(code) {
  let original = code,
    intensity = "";
  if (code[0] === "-") {
    intensity = "Light ";
    code = code.slice(1);
  } else if (code[0] === "+") {
    intensity = "Heavy ";
    code = code.slice(1);
  } else if (code.startsWith("VC")) {
    intensity = "In the vicinity: ";
    code = code.slice(2);
  }
  const parts = [];
  for (let i = 0; i < code.length; ) {
    const pair = code.slice(i, i + 2);
    if (WX[pair]) {
      parts.push(WX[pair]);
      i += 2;
    } else {
      i++;
    }
  }
  return {
    code: original,
    description:
      intensity +
      (parts.length ? parts.join(" ") : "Unrecognized weather group"),
  };
}

function parse(raw) {
  const clean = raw.trim().toUpperCase().replace(/\s+/g, " ");
  if (!clean) throw new Error("Enter a METAR to decode.");
  const tokens = clean.split(" ");
  const out = {
    raw: clean,
    type: "METAR",
    station: null,
    time: null,
    wind: null,
    variableWind: null,
    visibility: null,
    weather: [],
    clouds: [],
    temp: null,
    dew: null,
    preciseTemp: null,
    preciseDew: null,
    altimeter: null,
    remarks: null,
    decodedRemarks: [],
  };
  let i = 0;
  if (["METAR", "SPECI"].includes(tokens[i])) out.type = tokens[i++];
  if (/^[A-Z0-9]{4}$/.test(tokens[i] || "")) out.station = tokens[i++];
  else
    throw new Error(
      "I could not identify a four-character station identifier at the start of this report.",
    );
  for (; i < tokens.length; i++) {
    let t = tokens[i];
    if (t === "RMK") {
      out.remarks = tokens.slice(i + 1).join(" ");
      parseRemarks(out);
      break;
    }
    if (/^(AUTO|COR|NIL)$/.test(t)) continue;
    let m;
    if ((m = t.match(/^(\d{2})(\d{2})(\d{2})Z$/))) {
      out.time = { code: t, day: +m[1], hour: +m[2], minute: +m[3] };
      continue;
    }
    if ((m = t.match(/^(VRB|\d{3})(\d{2,3})(G(\d{2,3}))?(KT|MPS|KMH)$/))) {
      out.wind = {
        code: t,
        direction: m[1],
        speed: +m[2],
        gust: m[4] ? +m[4] : null,
        unit: m[5],
      };
      continue;
    }
    if ((m = t.match(/^(\d{3})V(\d{3})$/))) {
      out.variableWind = { code: t, from: +m[1], to: +m[2] };
      continue;
    }
    const vis = parseVisibility(tokens, i);
    if (vis) {
      out.visibility = vis.data;
      i += vis.used - 1;
      continue;
    }
    if ((m = t.match(/^(FEW|SCT|BKN|OVC|VV)(\d{3}|\/\/\/)(CB|TCU)?$/))) {
      out.clouds.push({
        code: t,
        amount: m[1],
        feet: m[2] === "///" ? null : +m[2] * 100,
        type: m[3] || null,
      });
      continue;
    }
    if (/^(SKC|CLR|NSC|NCD)$/.test(t)) {
      out.clouds.push({ code: t, amount: t, feet: null, type: null });
      continue;
    }
    if ((m = t.match(/^(M?\d{2}|\/\/)\/(M?\d{2}|\/\/)$/))) {
      out.temp = tempValue(m[1]);
      out.dew = tempValue(m[2]);
      out.tempCode = t;
      continue;
    }
    if ((m = t.match(/^A(\d{4})$/))) {
      out.altimeter = {
        code: t,
        inhg: +m[1] / 100,
        hpa: Math.round((+m[1] / 100) * 33.8639),
      };
      continue;
    }
    if ((m = t.match(/^Q(\d{4})$/))) {
      out.altimeter = {
        code: t,
        hpa: +m[1],
        inhg: (+m[1] / 33.8639).toFixed(2),
      };
      continue;
    }
    if (/^[-+]?([A-Z]{2}){1,4}$/.test(t) || /^VC([A-Z]{2})+$/.test(t)) {
      const wx = decodeWeather(t);
      if (wx.description !== "Unrecognized weather group") out.weather.push(wx);
    }
  }
  return out;
}

function remarkTemp(sign, digits) {
  return (sign === "1" ? -1 : 1) * (Number(digits) / 10);
}
function remarkTimeText(v) {
  if (!v) return "";
  return v.length === 2
    ? `${v} minutes past the hour`
    : `${v.slice(0, 2)}:${v.slice(2)} UTC`;
}
function precipName(code) {
  const names = {
    RA: "Rain",
    DZ: "Drizzle",
    SN: "Snow",
    SG: "Snow grains",
    PL: "Ice pellets",
    GR: "Hail",
    GS: "Small hail/snow pellets",
    UP: "Unknown precipitation",
    FZRA: "Freezing rain",
    FZDZ: "Freezing drizzle",
    SHRA: "Rain showers",
    SHSN: "Snow showers",
  };
  return names[code] || code;
}
function decodePrecipTiming(t) {
  const m = t.match(/^([A-Z]{2,4})(?:B(\d{2}|\d{4}))?(?:E(\d{2}|\d{4}))?$/);
  if (!m || (!m[2] && !m[3])) return null;
  const valid = [
    "RA",
    "DZ",
    "SN",
    "SG",
    "PL",
    "GR",
    "GS",
    "UP",
    "FZRA",
    "FZDZ",
    "SHRA",
    "SHSN",
    "TS",
  ];
  if (!valid.includes(m[1])) return null;
  const name = m[1] === "TS" ? "Thunderstorm" : precipName(m[1]);
  const parts = [];
  if (m[2]) parts.push(`began at ${remarkTimeText(m[2])}`);
  if (m[3]) parts.push(`ended at ${remarkTimeText(m[3])}`);
  return `${name} ${parts.join(" and ")}`;
}
function pressureTendencyText(a) {
  return (
    {
      0: "increasing, then decreasing; same or higher than 3 hours ago",
      1: "increasing, then steady; higher than 3 hours ago",
      2: "increasing steadily or unsteadily",
      3: "decreasing or steady, then increasing; higher than 3 hours ago",
      4: "steady",
      5: "decreasing, then increasing; same or lower than 3 hours ago",
      6: "decreasing, then steady; lower than 3 hours ago",
      7: "decreasing steadily or unsteadily",
      8: "steady or increasing, then decreasing; lower than 3 hours ago",
    }[a] || "tendency code unavailable"
  );
}
function decodeRemarkToken(t, d) {
  let m, text;

  if (t === "AO1")
    return "Automated station without a precipitation discriminator";

  if (t === "AO2")
    return "Automated station with a precipitation discriminator";

  if (t === "$")
    return "Automated station maintenance/check indicator";

  if (/^TS(?:[BE]\d{2,4})+$/.test(t)) {
    const events = [...t.slice(2).matchAll(/([BE])(\d{2}|\d{4})/g)];

    return events
      .map((event) => {
        const action =
          event[1] === "B"
            ? "Thunderstorm began"
            : "Thunderstorm ended";

        return `${action} at ${remarkTimeText(event[2])}`;
      })
      .join("; ");
  }

  if (/^LTG(?:IC|CC|CG|CA)+$/.test(t)) {
    const codes = t.slice(3);
    const types = [];

    for (let i = 0; i < codes.length; i += 2) {
      const type = codes.slice(i, i + 2);

      if (type === "IC")
        types.push("in-cloud");
      else if (type === "CC")
        types.push("cloud-to-cloud");
      else if (type === "CG")
        types.push("cloud-to-ground");
      else if (type === "CA")
        types.push("cloud-to-air");
    }

    return types.length
      ? `${types.join(" and ")} lightning`
      : "Lightning";
  }

  const sensor = {
    PWINO: "Precipitation identifier information not available",
    PNO: "Precipitation amount not available",
    FZRANO: "Freezing-rain sensor information not available",
    TSNO: "Thunderstorm information not available",
    RVRNO: "Runway visual range information not available",
    SLPNO: "Sea-level pressure not available",
  };

  if (sensor[t])
    return sensor[t];

  if (t === "PRESRR")
    return "Pressure rising rapidly";

  if (t === "PRESFR")
    return "Pressure falling rapidly";

  if (t === "OCNL")
    return "Occasional";

  if (t === "FRQ")
    return "Frequent";

  if (t === "CONS")
    return "Continuous";

  if (t === "OHD")
    return "Overhead";

  if (t === "MOV")
    return "Moving";

  if (t === "TS")
    return "Thunderstorm";

  if (/^(N|NE|E|SE|S|SW|W|NW)$/.test(t)) {
    const directions = {
      N: "North",
      NE: "Northeast",
      E: "East",
      SE: "Southeast",
      S: "South",
      SW: "Southwest",
      W: "West",
      NW: "Northwest",
    };

    return directions[t];
  }

  if ((text = decodePrecipTiming(t)))
    return text;

  if ((m = t.match(/^SLP(\d{3})$/))) {
    let h = Number(m[1]) / 10;
    h += h < 50 ? 1000 : 900;

    return `Sea-level pressure ${h.toFixed(1)} hPa`;
  }

  if ((m = t.match(/^P(\d{4})$/))) {
    const n = Number(m[1]);

    return n === 0
      ? "Trace precipitation since the previous hourly observation (<0.01 in)"
      : `Hourly precipitation ${(n / 100).toFixed(2)} in since the previous hourly observation`;
  }

  if ((m = t.match(/^6(\d{4})$/))) {
    const n = Number(m[1]);

    return n === 0
      ? "Trace precipitation during the applicable 3- or 6-hour period (<0.01 in)"
      : `${(n / 100).toFixed(2)} in precipitation during the applicable 3- or 6-hour period`;
  }

  if ((m = t.match(/^7(\d{4})$/))) {
    const n = Number(m[1]);

    return n === 0
      ? "Trace precipitation during the past 24 hours (<0.01 in)"
      : `${(n / 100).toFixed(2)} in precipitation during the past 24 hours`;
  }

  if ((m = t.match(/^T([01])(\d{3})([01])(\d{3})$/))) {
    d.preciseTemp = remarkTemp(m[1], m[2]);
    d.preciseDew = remarkTemp(m[3], m[4]);

    return `Precise temperature ${d.preciseTemp.toFixed(1)}°C; dew point ${d.preciseDew.toFixed(1)}°C`;
  }
  if ((m = t.match(/^1([01])(\d{3})$/)))
    return `6-hour maximum temperature ${remarkTemp(m[1], m[2]).toFixed(1)}°C`;

  if ((m = t.match(/^2([01])(\d{3})$/)))
    return `6-hour minimum temperature ${remarkTemp(m[1], m[2]).toFixed(1)}°C`;

  if ((m = t.match(/^4([01])(\d{3})([01])(\d{3})$/)))
    return `24-hour maximum temperature ${remarkTemp(m[1], m[2]).toFixed(1)}°C; minimum ${remarkTemp(m[3], m[4]).toFixed(1)}°C`;

  if ((m = t.match(/^5([0-8])(\d{3})$/)))
    return `3-hour pressure tendency: ${pressureTendencyText(m[1])}; change ${(Number(m[2]) / 10).toFixed(1)} hPa`;

  if ((m = t.match(/^CIG(\d{3})V(\d{3})$/)))
    return `Ceiling varying between ${Number(m[1]) * 100} and ${Number(m[2]) * 100} ft`;

  return null;
}
