function parseMany(raw) {
  const lines = raw
    .split(/\r?\n/)
    .map((x) => x.trim())
    .filter(Boolean);
  if (!lines.length) throw new Error("Enter a METAR to decode.");
  return lines.map(parse).sort((a, b) => {
    if (!a.time || !b.time) return 0;
    return (
      a.time.day * 1440 +
      a.time.hour * 60 +
      a.time.minute -
      (b.time.day * 1440 + b.time.hour * 60 + b.time.minute)
    );
  });
}

function flightCategory(d) {
  let ceiling = null;
  d.clouds
    .filter((c) => ["BKN", "OVC", "VV"].includes(c.amount) && c.feet !== null)
    .forEach((c) => {
      if (ceiling === null || c.feet < ceiling) ceiling = c.feet;
    });
  const vis = d.visibility?.miles;
  let rank = 0,
    reason = []; // 0 VFR, 1 MVFR, 2 IFR, 3 LIFR
  if (ceiling !== null) {
    if (ceiling < 500) {
      rank = Math.max(rank, 3);
      reason.push(`ceiling ${ceiling} ft`);
    } else if (ceiling < 1000) {
      rank = Math.max(rank, 2);
      reason.push(`ceiling ${ceiling} ft`);
    } else if (ceiling <= 3000) {
      rank = Math.max(rank, 1);
      reason.push(`ceiling ${ceiling} ft`);
    }
  }
  if (vis !== null && vis !== undefined) {
    if (vis < 1) {
      rank = Math.max(rank, 3);
      reason.push(`visibility ${vis} SM`);
    } else if (vis < 3) {
      rank = Math.max(rank, 2);
      reason.push(`visibility ${vis} SM`);
    } else if (vis <= 5) {
      rank = Math.max(rank, 1);
      reason.push(`visibility ${vis} SM`);
    }
  }
  if (ceiling === null && (vis === null || vis === undefined)) return null;
  return {
    name: ["VFR", "MVFR", "IFR", "LIFR"][rank],
    reason: reason.length ? reason.join(" · ") : "ceiling and visibility",
  };
}

function tokenInfo(token, inRemarks = false) {
  let m;
  if (token === "METAR")
    return { title: "Report Type", meaning: "Routine aviation weather report" };
  if (token === "SPECI")
    return { title: "Report Type", meaning: "Special aviation weather report" };
  if (token === "AUTO")
    return { title: "Report Modifier", meaning: "Fully automated observation" };
  if (token === "COR")
    return { title: "Report Modifier", meaning: "Corrected report" };
  if (token === "RMK")
    return { title: "Remarks", meaning: "Remarks section begins" };
  if (/^[A-Z0-9]{4}$/.test(token) && !inRemarks)
    return { title: "Station", meaning: `Reporting station: ${token}` };
  if ((m = token.match(/^(\d{2})(\d{2})(\d{2})Z$/)))
    return {
      title: "Observation Time",
      meaning: `Observed on day ${+m[1]} at ${m[2]}:${m[3]} UTC`,
    };
  if ((m = token.match(/^(VRB|\d{3})(\d{2,3})(G(\d{2,3}))?(KT|MPS|KMH)$/))) {
    const dir =
      m[1] === "VRB"
        ? "variable direction"
        : `from ${m[1]}° (${compass(+m[1])})`;
    return {
      title: "Wind",
      meaning: `Wind ${dir} at ${+m[2]} ${m[5] === "KT" ? "knots" : m[5]}${m[4] ? `, gusting ${+m[4]}` : ""}`,
    };
  }
  if ((m = token.match(/^(\d{3})V(\d{3})$/)))
    return {
      title: "Wind — Variable Direction",
      meaning: `Wind direction varying between ${m[1]}° and ${m[2]}°`,
    };
  if (token === "CAVOK")
    return {
      title: "Visibility / Sky",
      meaning:
        "Visibility 10 km or more, no significant weather, and no significant cloud below CAVOK limits",
    };
  if (/^(M|P)?(?:\d+)?(?:\d\/\d)?SM$/.test(token))
    return {
      title: "Visibility",
      meaning: `Prevailing visibility: ${token.replace("SM", "")} statute mile(s)`,
    };
  if (/^\d{4}$/.test(token) && !inRemarks)
    return {
      title: "Visibility",
      meaning: `Prevailing visibility: ${Number(token) / 1000} km`,
    };
  if ((m = token.match(/^(FEW|SCT|BKN|OVC|VV)(\d{3}|\/\/\/)(CB|TCU)?$/))) {
    const feet =
      m[2] === "///" ? "height unavailable" : `${+m[2] * 100} ft AGL`;
    return {
      title: "Clouds",
      meaning: `${CLOUD[m[1]] || m[1]} at ${feet}${m[3] === "CB" ? " · cumulonimbus" : m[3] === "TCU" ? " · towering cumulus" : ""}`,
    };
  }
  if (CLOUD[token]) return { title: "Clouds", meaning: CLOUD[token] };
  if ((m = token.match(/^(M?\d{2}|\/\/)\/(M?\d{2}|\/\/)$/))) {
    const t = tempValue(m[1]),
      d = tempValue(m[2]);
    return {
      title: "Temperature / Dew Point",
      meaning: `Temperature ${t == null ? "unavailable" : t + "°C"}; dew point ${d == null ? "unavailable" : d + "°C"}`,
    };
  }
  if ((m = token.match(/^A(\d{4})$/)))
    return {
      title: "Altimeter",
      meaning: `Altimeter setting ${(Number(m[1]) / 100).toFixed(2)} inHg`,
    };
  if ((m = token.match(/^Q(\d{4})$/)))
    return { title: "Altimeter", meaning: `Altimeter setting ${+m[1]} hPa` };
  if (token === "AO1")
    return {
      title: "Remarks — Station Type",
      meaning: "Automated station without a precipitation discriminator",
    };
  if (token === "AO2")
    return {
      title: "Remarks — Station Type",
      meaning: "Automated station with a precipitation discriminator",
    };
  if (token === "PWINO")
    return {
      title: "Remarks — Sensor Status",
      meaning: "Precipitation identifier sensor not operating",
    };
  if ((m = token.match(/^T([01])(\d{3})([01])(\d{3})$/))) {
    const sg = (a, n) => (a === "1" ? -1 : 1) * (+n / 10);
    return {
      title: "Remarks — Precise Temperature",
      meaning: `Precise temperature ${sg(m[1], m[2]).toFixed(1)}°C; dew point ${sg(m[3], m[4]).toFixed(1)}°C`,
    };
  }
  if ((m = token.match(/^SLP(\d{3})$/))) {
    let h = +m[1] / 10;
    h += h < 50 ? 1000 : 900;
    return {
      title: "Remarks — Sea-Level Pressure",
      meaning: `Sea-level pressure ${h.toFixed(1)} hPa`,
    };
  }
  if (inRemarks) {
    const dummy = { preciseTemp: null, preciseDew: null };
    const decoded = decodeRemarkToken(token, dummy);
    if (decoded) return { title: "Remarks", meaning: decoded };
  }
  if (/^[-+]?([A-Z]{2}){1,4}$/.test(token) || /^VC([A-Z]{2})+$/.test(token)) {
    const wx = decodeWeather(token);
    if (!wx.description.includes("Unrecognized"))
      return { title: "Present Weather", meaning: wx.description };
  }
  return {
    title: inRemarks ? "Remarks" : "METAR Group",
    meaning: inRemarks
      ? "Remark code not yet decoded by this app"
      : "METAR group not yet decoded by this app",
  };
}
function interactiveRaw(ds) {
  return ds
    .map((d, reportIndex) => {
      let inRemarks = false;
      const parts = d.raw
        .split(/\s+/)
        .map((token, i) => {
          const info = tokenInfo(token, inRemarks);
          const html = `<span class="metar-token" tabindex="0" data-title="${escapeHtml(info.title)}" data-meaning="${escapeHtml(info.meaning)}" aria-label="${escapeHtml(info.title + ": " + token + ". " + info.meaning)}">${escapeHtml(token)}</span>`;
          if (token === "RMK") inRemarks = true;
          return html;
        })
        .join(" ");
      return `<span class="raw-report" data-report="${reportIndex + 1}">${parts}</span>`;
    })
    .join("\n");
}
function escapeHtml(s) {
  return String(s).replace(
    /[&<>\"]/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c],
  );
}
