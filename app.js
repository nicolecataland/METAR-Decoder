async function decode() {
  try {
    if (!stationDataReady) await stationDataPromise;
    const ds = parseMany(input.value);
    render(ds[ds.length - 1]);
    renderTrend(ds);
    $("#rawOutput").innerHTML = interactiveRaw(ds);
    bindRawTooltips();
  } catch (e) {
    errorBox.textContent = e.message;
    errorBox.hidden = false;
    results.hidden = true;
  }
}
