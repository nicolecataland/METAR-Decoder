// Station metadata is generated by scripts/update_stations.py and served as static JSON.
let STATIONS = {};
let stationDataReady = false;

async function loadStationDatabase() {
  const status = $("#stationDataStatus");
  try {
    const response = await fetch("./data/stations.json", { cache: "no-cache" });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const data = await response.json();
    if (!data || typeof data !== "object" || Array.isArray(data))
      throw new Error("Unexpected station database format");
    STATIONS = data;
    stationDataReady = true;
    if (status)
      status.textContent = `Station database ready (${Object.keys(STATIONS).length.toLocaleString()} stations).`;
  } catch (err) {
    console.error("Station database failed to load:", err);
    STATIONS = {};
    stationDataReady = true;
    if (status)
      status.textContent =
        "Station metadata unavailable; decoder will use UTC.";
  }
}

