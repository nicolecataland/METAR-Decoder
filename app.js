function stationMeta(id) {
  return STATIONS[id] || null;
}
function observationDateUTC(t) {
  if (!t) return null;
  const now = new Date();
  let d = new Date(
    Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), t.day, t.hour, t.minute),
  );
  const diff = d - now;
  if (diff > 15 * 86400000)
    d = new Date(
      Date.UTC(
        now.getUTCFullYear(),
        now.getUTCMonth() - 1,
        t.day,
        t.hour,
        t.minute,
      ),
    );
  else if (diff < -20 * 86400000)
    d = new Date(
      Date.UTC(
        now.getUTCFullYear(),
        now.getUTCMonth() + 1,
        t.day,
        t.hour,
        t.minute,
      ),
    );
  return d;
}
function stationLocalTime(d) {
  if (!d.time) return "Observation time unavailable";
  const date = observationDateUTC(d.time),
    meta = stationMeta(d.station),
    tz = meta?.timezone;
  if (!tz)
    return `Day ${d.time.day}, ${String(d.time.hour).padStart(2, "0")}:${String(d.time.minute).padStart(2, "0")} UTC · local time unavailable`;
  try {
    return (
      new Intl.DateTimeFormat("en-US", {
        timeZone: tz,
        month: "short",
        day: "numeric",
        hour: "numeric",
        minute: "2-digit",
        hour12: true,
        timeZoneName: "short",
      }).format(date) + " (Local Time)"
    );
    // }).format(date);
  } catch (e) {
    return `Day ${d.time.day}, ${String(d.time.hour).padStart(2, "0")}:${String(d.time.minute).padStart(2, "0")} UTC`;
  }
}
function stationDescription(d) {
  const meta = stationMeta(d.station);
  if (!meta) return "Station metadata not in local database";
  return [meta.name, [meta.city, meta.region].filter(Boolean).join(", ")]
    .filter(Boolean)
    .join(" · ");
}

