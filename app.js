function parseRemarks(d) {
  if (!d.remarks) return;
  const rt = d.remarks.split(/\s+/);
  d.undecodedRemarks = [];
  for (let i = 0; i < rt.length; i++) {
    const t = rt[i];
    let m,
      text = null,
      code = t;
    if (
      t === "PK" &&
      rt[i + 1] === "WND" &&
      (m = (rt[i + 2] || "").match(/^(\d{3})(\d{2,3})\/(\d{2}|\d{4})$/))
    ) {
      code = `PK WND ${rt[i + 2]}`;
      text = `Peak wind from ${m[1]}° at ${Number(m[2])} knots at ${remarkTimeText(m[3])}`;
      i += 2;
    } else if (
      t === "WSHFT" &&
      (m = (rt[i + 1] || "").match(/^(\d{2}|\d{4})$/))
    ) {
      code = `WSHFT ${rt[i + 1]}`;
      text = `Wind shift began at ${remarkTimeText(m[1])}`;
      i++;
      if (rt[i + 1] === "FROPA") {
        code += " FROPA";
        text += " due to frontal passage";
        i++;
      }
    } else if (
      (t === "TWR" || t === "SFC") &&
      rt[i + 1] === "VIS" &&
      rt[i + 2]
    ) {
      code = `${t} VIS ${rt[i + 2]}`;
      text = `${t === "TWR" ? "Tower" : "Surface"} visibility ${rt[i + 2]} statute mile(s)`;
      i += 2;
    } else if (t === "VISNO") {
      const loc =
        rt[i + 1] && !decodeRemarkToken(rt[i + 1], d) ? rt[i + 1] : null;
      code = loc ? `VISNO ${loc}` : t;
      text = `Visibility sensor information not available${loc ? ` at ${loc}` : ""}`;
      if (loc) i++;
    } else if (t === "CHINO") {
      const loc =
        rt[i + 1] && !decodeRemarkToken(rt[i + 1], d) ? rt[i + 1] : null;
      code = loc ? `CHINO ${loc}` : t;
      text = `Cloud-height indicator information not available${loc ? ` at ${loc}` : ""}`;
      if (loc) i++;
    } else if (t === "VIRGA") {
      const dir =
        rt[i + 1] && /^(N|NE|E|SE|S|SW|W|NW|ALQDS)$/.test(rt[i + 1])
          ? rt[i + 1]
          : null;
      code = dir ? `VIRGA ${dir}` : t;
      text = `Virga${dir ? ` ${dir} of the station` : ""}`;
      if (dir) i++;

      // Thunderstorm beginning/ending times:
      // TSB31, TSE28, TSB31E47, TSE28B31, TSE28B31E47, etc.
    } else if ((m = t.match(/^TS((?:B|E)\d{2,4})+$/))) {
      const events = [...t.slice(2).matchAll(/([BE])(\d{2}|\d{4})/g)];

      code = t;

      text = events
        .map((event) => {
          const action =
            event[1] === "B" ? "Thunderstorm began" : "Thunderstorm ended";

          return `${action} at ${remarkTimeText(event[2])}`;
        })
        .join("; ");

      // Lightning frequency/type/location:
      // e.g. OCNL LTGICCG OHD
    } else if (
      /^(OCNL|FRQ|CONS)$/.test(t) &&
      /^LTG[A-Z]+$/.test(rt[i + 1] || "")
    ) {
      const frequency = {
        OCNL: "Occasional",
        FRQ: "Frequent",
        CONS: "Continuous",
      }[t];

      const lightningToken = rt[i + 1];
      const lightningCodes = lightningToken.slice(3);

      const types = [];
      if (lightningCodes.includes("IC")) types.push("in-cloud");
      if (lightningCodes.includes("CC")) types.push("cloud-to-cloud");
      if (lightningCodes.includes("CG")) types.push("cloud-to-ground");
      if (lightningCodes.includes("CA")) types.push("cloud-to-air");

      code = `${t} ${lightningToken}`;
      text = `${frequency} ${types.join(" and ")} lightning`;

      i++;

      if (rt[i + 1] === "OHD") {
        code += " OHD";
        text += " overhead";
        i++;
      }
    } else if (t === "TS") {
      const parts = ["TS"];
      let location = "";
      let movement = "";

      if (rt[i + 1] === "OHD") {
        parts.push("OHD");
        location = " overhead";
        i++;
      }

      if (
        rt[i + 1] === "MOV" &&
        /^(N|NE|E|SE|S|SW|W|NW)$/.test(rt[i + 2] || "")
      ) {
        parts.push("MOV", rt[i + 2]);
        movement = `, moving ${rt[i + 2]}`;
        i += 2;
      }

      code = parts.join(" ");
      text = `Thunderstorm${location}${movement}`;
    } else text = decodeRemarkToken(t, d);

    if (text) d.decodedRemarks.push({ code, text });
    else d.undecodedRemarks.push(t);
  }
  if (d.undecodedRemarks.length)
    d.decodedRemarks.push({
      code: d.undecodedRemarks.join(" "),
      text: "Additional remark(s) not yet decoded by this app",
    });
}
function displayTemp(d, key) {
  const v =
    key === "temp" ? (d.preciseTemp ?? d.temp) : (d.preciseDew ?? d.dew);
  return v;
}
function skyTrend(d) {
  if (!d.clouds.length) return { code: "—", description: "" };
  const code = d.clouds.map((c) => c.code).join(" · ");
  const description = d.clouds
    .map((c) => {
      if (c.amount === "CLR") return "Clear";
      if (c.amount === "SKC") return "Sky clear";
      if (c.amount === "NSC") return "No significant cloud";
      if (c.amount === "NCD") return "No cloud detected";
      const label = CLOUD[c.amount] || c.amount;
      const height = c.feet !== null ? ` at ${c.feet.toLocaleString()} ft` : "";
      const type =
        c.type === "CB"
          ? " cumulonimbus"
          : c.type === "TCU"
            ? " towering cumulus"
            : "";
      return `${label}${height}${type}`;
    })
    .join(" · ");
  return { code, description };
}
function trendArrow(curr, prev, decimals = 1) {
  if (curr == null || prev == null) return "";
  const diff = curr - prev;
  if (Math.abs(diff) < Math.pow(10, -decimals) / 2) return "→";
  return diff > 0
    ? `↑ +${diff.toFixed(decimals)}`
    : `↓ ${diff.toFixed(decimals)}`;
}
